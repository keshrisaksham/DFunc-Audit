#!/usr/bin/python3
import argparse
import requests

parser = argparse.ArgumentParser(
    prog="dfunc-audit.py",
    formatter_class=argparse.RawDescriptionHelpFormatter,
    description=(
        "Checks whether disable_functions in a phpinfo() dump still leaves room for\n"
        "LD_PRELOAD-based exploitation, given the PHP modules installed on the server."
    ),
    epilog=(
        "examples:\n"
        "  Audit a live phpinfo page:\n"
        "    dfunc-audit.py --url https://example.com/phpinfo.php\n\n"
        "  Audit a phpinfo dump you saved locally:\n"
        "    dfunc-audit.py --file dir/phpinfo\n\n"
        "  Generate a standalone checker script to run directly on the server:\n"
        "    dfunc-audit.py --gen-checker check.php\n\n"
        "  ...testing your own functions as well as the built-in list:\n"
        "    dfunc-audit.py --gen-checker check.php --functions mymodule_func --include-defaults\n"
    ),
)

source = parser.add_argument_group("where to read the phpinfo from")
source.add_argument("--url", metavar="URL",
                     help="PHPinfo URL, e.g. https://example.com/phpinfo.php")
source.add_argument("--file", metavar="PATH",
                     help="Local phpinfo file, e.g. dir/phpinfo")

checker = parser.add_argument_group("generate a standalone checker script instead")
checker.add_argument("--gen-checker", metavar="OUTPUT_FILE", dest="gen_checker",
                      help="Write a self-contained PHP script to OUTPUT_FILE. Run it "
                           "directly on a server to see, per function, whether it is "
                           "actually ENABLED or DISABLED right now, rather than guessing "
                           "from a phpinfo dump.")
checker.add_argument("--functions", metavar="LIST",
                      help="Comma-separated function names to test instead of the "
                           "built-in dangerous-functions list.")
checker.add_argument("--include-defaults", action="store_true", dest="include_defaults",
                      help="Test the built-in dangerous-functions list as well as "
                           "--functions, instead of replacing it.")
checker.add_argument("--enabled-only", action="store_true", dest="enabled_only",
                      help="Only print functions that come back ENABLED; hide the "
                           "disabled/unavailable ones.")

args = parser.parse_args()

class colors:
    reset  = '\033[0m'
    border = '\033[1;36m'   # bold cyan
    tag    = '\033[2;35m'   # dim violet

BANNER_ART = [
    r"    ____  ________  ___   ________   ___   __  ______  __________",
    r"   / __ \/ ____/ / / / | / / ____/  /   | / / / / __ \/  _/_  __/",
    r"  / / / / /_  / / / /  |/ / /      / /| |/ / / / / / // /  / /   ",
    r" / /_/ / __/ / /_/ / /|  / /___   / ___ / /_/ / /_/ // /  / /    ",
    r"/_____/_/    \____/_/ |_/\____/  /_/  |_\____/_____/___/ /_/     ",
]
TAGLINE = "disable_functions security auditor"
WIDTH = max(len(l) for l in BANNER_ART)

GRAD_START = (0, 229, 255)    # cyan
GRAD_END   = (178, 102, 255)  # violet

def _rgb(c):
    return "\033[38;2;{};{};{}m".format(*c)

def _lerp(a, b, t):
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))

def _row(inner):
    return colors.border + "║ " + colors.reset + inner + colors.border + " ║" + colors.reset

def print_banner():
    print(colors.border + "╔" + "═" * (WIDTH + 2) + "╗" + colors.reset)
    print(_row(" " * WIDTH))
    n = len(BANNER_ART)
    for i, line in enumerate(BANNER_ART):
        t = i / (n - 1) if n > 1 else 0
        colored = _rgb(_lerp(GRAD_START, GRAD_END, t)) + line.ljust(WIDTH) + colors.reset
        print(_row(colored))
    print(_row(" " * WIDTH))
    print(_row(colors.tag + TAGLINE.center(WIDTH) + colors.reset))
    print(_row(" " * WIDTH))
    print(colors.border + "╚" + "═" * (WIDTH + 2) + "╝" + colors.reset)
    print()

print_banner()

dangerous_functions = ['pcntl_alarm','pcntl_fork','pcntl_waitpid','pcntl_wait','pcntl_wifexited','pcntl_wifstopped','pcntl_wifsignaled','pcntl_wifcontinued','pcntl_wexitstatus','pcntl_wtermsig','pcntl_wstopsig','pcntl_signal','pcntl_signal_get_handler','pcntl_signal_dispatch','pcntl_get_last_error','pcntl_strerror','pcntl_sigprocmask','pcntl_sigwaitinfo','pcntl_sigtimedwait','pcntl_exec','pcntl_getpriority','pcntl_setpriority','pcntl_async_signals','error_log','system','exec','shell_exec','popen','proc_open','passthru','link','symlink','syslog','ld','mail']

# Functions contributed by optional modules. Included by default in the
# generated checker since it tests each one live (function_exists), so it's
# harmless to list checks for modules that may not even be installed.
module_extra_functions = ['mb_send_mail', 'imap_open', 'imap_mail', 'libvirt_connect', 'gnupg_init']

CHECKER_PHP_HEADER = """<?php
// Diagnostic script generated by dfunc-audit.
// Run it on a server (CLI or over HTTP) to list, for each function name
// below, whether it is ENABLED or DISABLED on that server right now.

$functions = array(
"""

CHECKER_PHP_FOOTER_TEMPLATE = """);

$enabled_only = {enabled_only};

$disabled_ini = ini_get('disable_functions');
$disabled_list = array_map('trim', explode(',', $disabled_ini));

foreach ($functions as $f) {{
    if (function_exists($f)) {{
        $status = 'ENABLED';
    }} elseif (in_array($f, $disabled_list, true)) {{
        $status = 'DISABLED (listed in disable_functions)';
    }} else {{
        $status = 'DISABLED / NOT AVAILABLE';
    }}
    if ($enabled_only && $status !== 'ENABLED') {{
        continue;
    }}
    printf("%-30s %s\\n", $f, $status);
}}
"""

def generate_checker_script(functions, output_path, enabled_only=False):
    body = ""
    for f in functions:
        body += "    '" + f.replace("'", "\\'") + "',\n"
    footer = CHECKER_PHP_FOOTER_TEMPLATE.format(enabled_only='true' if enabled_only else 'false')
    with open(output_path, 'w') as fh:
        fh.write(CHECKER_PHP_HEADER + body + footer)
    print("\nWrote " + str(len(functions)) + " function checks to " + output_path)
    print("Run it on the server with: php " + output_path)

if args.gen_checker:
    if args.functions:
        check_list = [f.strip() for f in args.functions.split(',') if f.strip()]
        if args.include_defaults:
            for f in dangerous_functions + module_extra_functions:
                if f not in check_list:
                    check_list.append(f)
    else:
        check_list = dangerous_functions + module_extra_functions
    generate_checker_script(check_list, args.gen_checker, args.enabled_only)
    exit()

if args.url:
    url = args.url
    phpinfo = requests.get(url).text

elif args.file:
    phpinfofile = args.file
    with open(phpinfofile, 'r') as f:
        phpinfo = f.read()

else:
    parser.print_help()
    exit()

modules = []
inp = []

inp = phpinfo.split('disable_functions</td><td class="v">')[1].split("</")[0].split(',')[:-1]

if "mbstring.ini" in phpinfo:
    modules += ['mbstring']
    dangerous_functions += ['mb_send_mail']

if "imap.ini" in phpinfo:
    modules += ['imap']
    dangerous_functions += ['imap_open','imap_mail']

if "libvirt-php.ini" in phpinfo:
    modules += ['libvert']
    dangerous_functions += ['libvirt_connect']

if "gnupg.ini" in phpinfo:
    modules += ['gnupg']
    dangerous_functions += ['gnupg_init']

if "imagick.ini" in phpinfo:
    modules += ['imagick']

exploitable_functions = []

for i in dangerous_functions:
    if i not in inp:
        exploitable_functions.append(i)

if len(exploitable_functions) == 0:
    print('\nThe disable_functions seems strong')

else:
    print('\nPlease add the following functions in your disable_functions option: ')
    print(','.join(exploitable_functions))

